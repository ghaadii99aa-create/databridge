"""Public demo: seeding of shared sample data and cleanup of temporary visitor data.

Seeding (idempotent) creates, as shared read-only system data (owner_id NULL):
  * the SAMPLE retail dataset,
  * a cleaning pipeline and one successful run of it,
  * a PDF pipeline run report,
so the first visitor sees a populated dashboard without uploading anything.

Cleanup removes only visitor-owned data older than DEMO_RETENTION_HOURS, plus orphaned files
and generated row tables that no metadata row refers to. It never touches system data
(owner_id NULL), application settings, the Alembic version table, metadata tables, migrations
or anything outside the configured upload and report folders.
"""
from __future__ import annotations

import logging
import re
import threading
from datetime import datetime, timedelta, timezone
from typing import Any

from sqlalchemy import inspect, select
from sqlalchemy.exc import IntegrityError
from sqlalchemy.orm import Session

from app.core.config import get_settings
from app.db import get_engine, session_factory
from app.models import AppSetting, Dataset, Pipeline, PipelineRun, ProcessedDataset, Report
from app.services import etl, ingestion, tables
from app.services.cleaning import TransformConfig
from app.services.reports import builder

log = logging.getLogger(__name__)

SAMPLE_FILE = "retail_sales_sample.csv"
SAMPLE_NAME = "Retail sales (SAMPLE)"
SAMPLE_DESCRIPTION = ("Synthetic retail transactions with deliberately injected quality problems. Generated by "
                      "scripts/generate_sample_data.py — not real business data. Shared, read-only demonstration data.")
SAMPLE_PIPELINE = "Clean retail sales (SAMPLE)"
SEED_LOCK = "demo_seed_lock"
LAST_CLEANUP = "demo_last_cleanup"
ROW_TABLE = re.compile(r"^(stg|prc)_(\d+)$")
ORPHAN_FILE_GRACE = timedelta(hours=1)


def system_sample(session: Session) -> Dataset | None:
    return session.scalar(select(Dataset).where(Dataset.is_sample.is_(True), Dataset.owner_id.is_(None),
                                                Dataset.status == "ready").order_by(Dataset.id).limit(1))


def _acquire_seed_lock(session: Session) -> bool:
    """One worker seeds; others skip. A lock older than 10 minutes without a sample is stale."""
    existing = session.get(AppSetting, SEED_LOCK)
    if existing is not None:
        started = datetime.fromisoformat(existing.value.get("at")) if isinstance(existing.value, dict) else None
        if started and datetime.now(timezone.utc) - started < timedelta(minutes=10):
            return False
        session.delete(existing)
        session.commit()
    session.add(AppSetting(key=SEED_LOCK, value={"at": datetime.now(timezone.utc).isoformat()}))
    try:
        session.commit()
        return True
    except IntegrityError:
        session.rollback()
        return False


def seed(session: Session) -> dict[str, Any]:
    """Create the shared sample dataset, pipeline, run and report if they do not exist."""
    sample = system_sample(session)
    if sample and session.scalar(select(Pipeline.id).where(Pipeline.dataset_id == sample.id, Pipeline.owner_id.is_(None))):
        return {"seeded": False, "dataset_id": sample.id}
    if not _acquire_seed_lock(session):
        return {"seeded": False, "reason": "another worker is seeding"}
    try:
        if sample is None:
            path = get_settings().sample_dir / SAMPLE_FILE
            if not path.exists():
                log.error("demo sample file missing: %s", path)
                return {"seeded": False, "reason": "sample file missing"}
            with path.open("rb") as fh:
                sample = ingestion.ingest_upload(session, fh, SAMPLE_FILE, SAMPLE_NAME, SAMPLE_DESCRIPTION,
                                                 is_sample=True, owner_id=None)
        cfg = TransformConfig(required_columns=["transaction_id", "transaction_date"])
        pipeline = etl.create_pipeline(session, sample.id, SAMPLE_PIPELINE,
                                       "Shared demonstration pipeline: trims, normalises, de-duplicates, converts "
                                       "types and rejects invalid rows.", cfg, owner_id=None)
        run = etl.queue_run(session, pipeline.id)
        etl.execute_run(run.id)
        session.expire_all()
        run = session.get(PipelineRun, run.id)
        if run.status == "succeeded":
            builder.generate(session, "pipeline_run", "pdf", run_id=run.id, owner_id=None)
        log.info("demo data seeded", extra={"dataset_id": sample.id, "run_id": run.id, "status": run.status})
        return {"seeded": True, "dataset_id": sample.id, "run_id": run.id, "run_status": run.status}
    finally:
        session.rollback()
        lock = session.get(AppSetting, SEED_LOCK)
        if lock is not None:
            session.delete(lock)
            session.commit()


def _older(ts: datetime, cutoff: datetime) -> bool:
    if ts.tzinfo is None:
        ts = ts.replace(tzinfo=timezone.utc)
    return ts < cutoff


def cleanup(session: Session, now: datetime | None = None) -> dict[str, int]:
    """Delete expired visitor data and orphans. Safe to run repeatedly and concurrently."""
    settings = get_settings()
    now = now or datetime.now(timezone.utc)
    cutoff = now - timedelta(hours=settings.demo_retention_hours)
    engine = get_engine()
    counts = {"datasets": 0, "pipelines": 0, "reports": 0, "files": 0, "tables": 0, "errors": 0}

    # 1. visitor datasets (cascades to their pipelines, runs, assessments; drops stg_/prc_ tables and files)
    for ds in session.scalars(select(Dataset).where(Dataset.owner_id.is_not(None))).all():
        if _older(ds.created_at, cutoff):
            try:
                ingestion.delete_dataset(session, ds.id)
                counts["datasets"] += 1
            except Exception:
                session.rollback()
                counts["errors"] += 1
                log.exception("cleanup: dataset %s", ds.id)

    # 2. visitor pipelines on shared data (e.g. the sample), with their output tables
    for p in session.scalars(select(Pipeline).where(Pipeline.owner_id.is_not(None))).all():
        if _older(p.created_at, cutoff):
            try:
                etl.delete_pipeline(session, p.id)
                counts["pipelines"] += 1
            except Exception:  # a run still in progress is retried on the next pass
                session.rollback()
                counts["errors"] += 1

    # 3. visitor reports
    for rep in session.scalars(select(Report).where(Report.owner_id.is_not(None))).all():
        if _older(rep.created_at, cutoff):
            builder.delete_report(session, rep.id)
            counts["reports"] += 1

    # 4. orphaned files (no metadata row points at them), with a grace period for in-flight uploads
    referenced_uploads = set(session.scalars(select(Dataset.stored_filename)).all())
    referenced_reports = set(session.scalars(select(Report.stored_filename)).all())
    for directory, referenced in ((settings.upload_dir, referenced_uploads), (settings.report_dir, referenced_reports)):
        if not directory.exists():
            continue
        for f in directory.iterdir():
            if not f.is_file() or f.name in referenced:
                continue
            modified = datetime.fromtimestamp(f.stat().st_mtime, tz=timezone.utc)
            if now - modified > ORPHAN_FILE_GRACE:
                f.unlink(missing_ok=True)
                counts["files"] += 1

    # 5. orphaned generated row tables (only names matching stg_<n> / prc_<n>)
    dataset_ids = {str(i) for i in session.scalars(select(Dataset.id)).all()}
    output_tables = set(session.scalars(select(ProcessedDataset.table_name)).all())
    active_runs = {str(i) for i in session.scalars(
        select(PipelineRun.id).where(PipelineRun.status.in_(("pending", "running")))).all()}
    for name in inspect(engine).get_table_names():
        m = ROW_TABLE.match(name)
        if not m:
            continue
        kind, ident = m.groups()
        orphan = (kind == "stg" and ident not in dataset_ids) or \
                 (kind == "prc" and name not in output_tables and ident not in active_runs)
        if orphan:
            tables.drop_table(engine, name)
            counts["tables"] += 1

    record = session.get(AppSetting, LAST_CLEANUP) or AppSetting(key=LAST_CLEANUP)
    record.value = {"at": now.isoformat(), **counts}
    session.merge(record)
    session.commit()
    log.info("demo cleanup finished", extra=counts)
    return counts


class CleanupScheduler:
    """Runs cleanup in a background thread every DEMO_CLEANUP_INTERVAL_MINUTES.

    Retention is 24 hours by default, so with an hourly pass visitor data is removed between
    24 and 25 hours after it was created ("daily cleanup").
    """

    def __init__(self) -> None:
        self._stop = threading.Event()
        self._thread: threading.Thread | None = None

    def start(self) -> None:
        if self._thread is None:
            self._thread = threading.Thread(target=self._loop, name="demo-cleanup", daemon=True)
            self._thread.start()

    def stop(self) -> None:
        self._stop.set()

    def _loop(self) -> None:
        interval = get_settings().demo_cleanup_interval_minutes * 60
        delay = 60  # first pass shortly after start-up, then every interval
        while not self._stop.wait(timeout=delay):
            delay = interval
            try:
                with session_factory()() as session:
                    seed(session)  # restores the shared sample if it is ever missing
                    cleanup(session)
            except Exception:
                log.exception("demo cleanup failed")


def demo_info(session: Session | None = None) -> dict[str, Any]:
    s = get_settings()
    info: dict[str, Any] = {
        "demo_mode": s.demo_mode,
        "max_upload_mb": s.max_upload_mb, "max_rows": s.max_rows, "max_columns": s.max_columns,
        "retention_hours": s.demo_retention_hours if s.demo_mode else None,
        "max_datasets_per_visitor": s.demo_max_datasets_per_visitor if s.demo_mode else None,
        "max_pipelines_per_visitor": s.demo_max_pipelines_per_visitor if s.demo_mode else None,
    }
    if session is not None and s.demo_mode:
        last = session.get(AppSetting, LAST_CLEANUP)
        info["last_cleanup"] = last.value.get("at") if last and isinstance(last.value, dict) else None
    return info

