import { useMutation, useQuery } from "@tanstack/react-query";
import { Calculator, Send, Sparkles } from "lucide-react";
import { useState } from "react";
import { Link } from "react-router-dom";
import { z } from "zod";

import { api } from "@/api/endpoints";
import type { AnalystAnswer } from "@/api/types";
import { Button, EmptyState, ErrorState, LoadingBlock, Notice, PageHeader } from "@/components/ui/primitives";
import { SourcePicker, useSource } from "@/features/explorer/SourcePicker";

const SUGGESTIONS = [
  "Summarize this dataset in simple language",
  "Which columns have the most missing values?",
  "Are there unusual records?",
  "What are the main patterns in this dataset?",
  "What are the most important findings?",
  "What business insights can be extracted?",
];
const questionSchema = z.string().trim().min(3, "Ask a question of at least 3 characters.").max(500, "Keep the question under 500 characters.");

function Answer({ a }: { a: AnalystAnswer }) {
  const [showProfile, setShowProfile] = useState(false);
  return (
    <article className="panel">
      <header className="border-b border-stone-line px-5 py-3.5">
        <p className="text-base font-medium text-ink">{a.question}</p>
      </header>

      {a.ai && (
        <section className="border-b border-stone-line px-5 py-4" aria-label="AI-generated analysis">
          <div className="mb-2 flex items-center gap-2 text-sm font-medium text-[#38557A]">
            <Sparkles className="h-4 w-4" aria-hidden /> {a.ai.label}
          </div>
          {a.ai.error ? (
            <p className="text-base text-clay-deep">The AI provider returned an error: {a.ai.error} The statistical answer below is unaffected.</p>
          ) : (
            <div className="max-w-[72ch] whitespace-pre-wrap text-base leading-relaxed text-ink">{a.ai.text}</div>
          )}
          <p className="mt-3 text-xs text-ink-muted">
            Generated by a language model from the dataset profile; verify figures against the statistical analysis.
            {a.ai.usage?.input_tokens != null && ` ${a.ai.usage.input_tokens} input / ${a.ai.usage.output_tokens} output tokens.`}
          </p>
        </section>
      )}

      <section className="px-5 py-4" aria-label="Statistical analysis">
        <div className="mb-3 flex items-center gap-2 text-sm font-medium text-forest-deep">
          <Calculator className="h-4 w-4" aria-hidden /> {a.statistical.label}
        </div>
        <dl className="max-w-[78ch] space-y-3">
          {a.statistical.findings.map((f, i) => (
            <div key={i}>
              <dt className="text-base font-medium text-ink">{f.title}</dt>
              <dd className="num text-base text-ink-soft">{f.detail}</dd>
            </div>
          ))}
        </dl>
      </section>

      {a.shared_profile && (
        <footer className="border-t border-stone-line px-5 py-3">
          <button className="link text-sm" onClick={() => setShowProfile((s) => !s)}>
            {showProfile ? "Hide" : "Show"} exactly what was sent to the AI provider
          </button>
          {showProfile && (
            <pre className="mt-3 max-h-80 overflow-auto rounded bg-paper p-3 text-xs text-ink-soft ring-1 ring-stone-line">
              {JSON.stringify(a.shared_profile, null, 2)}
            </pre>
          )}
        </footer>
      )}
    </article>
  );
}

export default function AnalystPage() {
  const { sources, source, sourceId, setSource, isLoading } = useSource();
  const status = useQuery({ queryKey: ["analyst-status"], queryFn: api.analyst.status, staleTime: 60_000 });
  const [question, setQuestion] = useState("");
  const [error, setError] = useState<string | null>(null);
  const [answers, setAnswers] = useState<AnalystAnswer[]>([]);
  const ask = useMutation({
    mutationFn: (q: string) => api.analyst.ask(sourceId!, q),
    onSuccess: (a) => { setAnswers((prev) => [a, ...prev].slice(0, 10)); setQuestion(""); },
  });

  const submit = (q: string) => {
    const r = questionSchema.safeParse(q);
    if (!r.success) { setError(r.error.issues[0].message); return; }
    setError(null);
    ask.mutate(r.data);
  };

  return (
    <>
      <PageHeader title="AI analyst" description="Ask questions about a dataset. Every answer includes statistics computed by DataBridge; an AI-written answer is added only when a provider is configured on the server."
        actions={sources.length > 0 && <SourcePicker sources={sources} value={sourceId} onChange={(id) => { setSource(id); setAnswers([]); }} />} />

      {status.data && (
        <div className="mb-6">
          {status.data.configured
            ? <Notice><strong className="text-ink">AI provider configured.</strong> {status.data.message} Only a profile (column statistics, quality findings and 5 sample rows) is sent, never the full dataset.</Notice>
            : <Notice tone="warn"><strong className="text-ink">No AI provider connected.</strong> {status.data.message}</Notice>}
        </div>
      )}

      {isLoading && <LoadingBlock />}
      {!isLoading && sources.length === 0 && <EmptyState title="No data to analyse"><Link to="/datasets" className="link">Add a dataset</Link> to ask questions about it.</EmptyState>}

      {source && (
        <div className="grid grid-cols-[minmax(0,1fr)] gap-8 lg:grid-cols-[300px_minmax(0,1fr)]">
          <aside>
            <form onSubmit={(e) => { e.preventDefault(); submit(question); }}>
              <label htmlFor="q" className="label">Your question about {source.dataset_name}</label>
              <textarea id="q" className="field h-28 py-2" value={question} maxLength={500} onChange={(e) => setQuestion(e.target.value)}
                placeholder="e.g. Which region generates the most revenue?" aria-invalid={!!error}
                onKeyDown={(e) => { if (e.key === "Enter" && (e.metaKey || e.ctrlKey)) submit(question); }} />
              {error && <p className="mt-1 text-sm text-clay-deep" role="alert">{error}</p>}
              <Button type="submit" variant="primary" className="mt-2 w-full" loading={ask.isPending} icon={<Send className="h-4 w-4" />}>Ask</Button>
            </form>
            <div className="mt-6">
              <div className="mb-2 text-sm text-ink-muted">Common questions</div>
              <ul className="space-y-1">
                {SUGGESTIONS.map((s) => (
                  <li key={s}><button className="w-full rounded px-2 py-1.5 text-left text-sm text-ink-soft hover:bg-stone hover:text-ink disabled:opacity-50"
                    disabled={ask.isPending} onClick={() => { setQuestion(s); submit(s); }}>{s}</button></li>
                ))}
              </ul>
            </div>
          </aside>
          <div className="space-y-5" aria-live="polite">
            {ask.isPending && <div className="panel p-5"><LoadingBlock rows={5} /></div>}
            {ask.error && <ErrorState error={ask.error} />}
            {answers.length === 0 && !ask.isPending && (
              <p className="rounded-md border border-dashed border-stone-dark px-5 py-8 text-base text-ink-muted">
                Answers appear here, newest first. Pick a common question to start.
              </p>
            )}
            {answers.map((a, i) => <Answer key={answers.length - i} a={a} />)}
          </div>
        </div>
      )}
    </>
  );
}
